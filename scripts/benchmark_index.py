"""Measure NumPy vs FAISS search latency on random vectors and write a Markdown table.

Usage (from the project root):
    python scripts/benchmark_index.py                       # 1k, 10k, 100k at dim 768
    python scripts/benchmark_index.py --sizes 1000 --dim 64 --output out.md

Every number in the output is measured on the machine running the script.
"""

import argparse
import platform
import statistics
import sys
import time
from datetime import date
from pathlib import Path

import faiss
import numpy as np

# Let the script import ragsearch when run as `python scripts/benchmark_index.py`.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ragsearch.faiss_index import FaissIndex
from ragsearch.index import Index, VectorIndex

K = 10


def measure(backend: type[Index], vectors: np.ndarray, queries: np.ndarray) -> tuple[float, float]:
    """Return (build time in ms, median search time per query in ms)."""
    items = [{"id": i} for i in range(len(vectors))]
    start = time.perf_counter()
    index = backend(vectors.shape[1])
    index.add(vectors, items)
    build_ms = (time.perf_counter() - start) * 1000

    index.search(queries[0], k=K)  # warm-up, not timed
    timings = []
    for query in queries:
        start = time.perf_counter()
        index.search(query, k=K)
        timings.append((time.perf_counter() - start) * 1000)
    return build_ms, statistics.median(timings)


def run(sizes: list[int], dim: int, n_queries: int, seed: int = 0) -> list[list[str]]:
    rng = np.random.default_rng(seed)
    queries = rng.standard_normal((n_queries, dim), dtype=np.float32)
    rows = []
    for n in sizes:
        vectors = rng.standard_normal((n, dim), dtype=np.float32)
        np_build, np_search = measure(VectorIndex, vectors, queries)
        fa_build, fa_search = measure(FaissIndex, vectors, queries)
        rows.append([
            str(n),
            f"{np_build:.4g}", f"{fa_build:.4g}",
            f"{np_search:.4g}", f"{fa_search:.4g}",
            f"{np_search / fa_search:.3g}x",
        ])
        print(f"n={n}: numpy {np_search:.4g} ms/query, faiss {fa_search:.4g} ms/query",
              file=sys.stderr)
    return rows


def to_markdown(rows: list[list[str]], dim: int, n_queries: int) -> str:
    header = ["Vectors", "NumPy build (ms)", "FAISS build (ms)",
              "NumPy search (ms/query)", "FAISS search (ms/query)", "FAISS speed-up"]
    lines = [
        "# Index benchmark: NumPy vs FAISS",
        "",
        f"Generated by `python scripts/benchmark_index.py` on {date.today().isoformat()}.",
        (f"Random normal vectors, dim {dim}, top-{K} search, median of {n_queries} queries "
        "(one warm-up query excluded). Build time includes normalising the vectors."),
        "",
        f"- Machine: {platform.platform()}, {platform.processor() or platform.machine()}",
        (f"- Python {platform.python_version()}, NumPy {np.__version__}, "
        f"faiss-cpu {faiss.__version__}"),
        "",
        "| " + " | ".join(header) + " |",
        "|" + "|".join("---:" for _ in header) + "|",
    ]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sizes", type=int, nargs="+", default=[1_000, 10_000, 100_000])
    parser.add_argument("--dim", type=int, default=768)
    parser.add_argument("--queries", type=int, default=200)
    parser.add_argument("--output", type=Path, default=Path("docs/benchmarks.md"))
    args = parser.parse_args(argv)

    rows = run(args.sizes, args.dim, args.queries)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(to_markdown(rows, args.dim, args.queries), encoding="utf-8")
    print(f"Wrote {args.output}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
